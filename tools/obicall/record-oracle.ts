/**
 * Records the oracle of the replay conformance (tests/fixtures/obicall/replay-oracle.json): the real recording and each of its torn variants given to the
 * REAL, staged `obicall replay`, and what it said — the records it read, how many were admitted, the last window sequence, and the status it stopped at.
 * Obicall is read-only here: its executable is run on copies in a temporary directory, and nothing of the Obicall checkout is written.
 *
 *   node tools/obicall/record-oracle.ts [path/to/obicall(.exe)]      (default: ../obicall-reference/stage-anytune/bin/obicall.exe, or $OBICALL_EXE)
 */
import { spawnSync } from 'node:child_process';
import crypto from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { tornVariants } from './torn-variants.ts';

const ROOT = path.resolve(import.meta.dirname, '..', '..');
const exe = process.argv[2] ?? process.env.OBICALL_EXE ?? path.resolve(ROOT, '..', 'obicall-reference', 'stage-anytune', 'bin', os.platform() === 'win32' ? 'obicall.exe' : 'obicall');
const demoFile = path.join(ROOT, 'tests', 'fixtures', 'obicall', 'demo.obr');
const demo = new Uint8Array(fs.readFileSync(demoFile));
const sha256 = (bytes: Uint8Array): string => crypto.createHash('sha256').update(bytes).digest('hex');

const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'anytune-oracle-'));
const variants: Record<string, unknown> = {};
try {
  for (const variant of tornVariants(demo)) {
    const file = path.join(dir, `${variant.name}.obr`);
    fs.writeFileSync(file, variant.bytes);
    const run = spawnSync(exe, ['replay', '--input', file, '--json'], { encoding: 'utf8' });
    if (run.status !== 0) throw new Error(`obicall replay failed on ${variant.name}: ${run.stderr}`);
    const said = JSON.parse(run.stdout);
    variants[variant.name] = {
      what: variant.what,
      sha256: sha256(variant.bytes),
      recordsTotal: said.records_total,
      admitted: said.admitted,
      finalWindowSeq: said.final_window_seq,
      stoppedAt: /status=([^)]+)\)/.exec(run.stderr)?.[1] ?? null,
    };
  }
} finally {
  fs.rmSync(dir, { recursive: true, force: true });
}

// `obicall doctor --json` says the version and ABI of the core library it loaded: "obicall 0.1.1 ABI 1.0"
const doctor = spawnSync(exe, ['doctor', '--json'], { encoding: 'utf8' });
const core = doctor.status === 0 ? (JSON.parse(doctor.stdout).checks as { name: string; detail: string }[]).find((check) => check.name === 'core_library')?.detail ?? null : null;
const oracle = {
  about: 'What the real, staged `obicall replay` (obicall ae5581a) said of AnyTune’s copy of demo.obr and of each torn variant tools/obicall/torn-variants.ts derives from it. Generated by tools/obicall/record-oracle.ts; never edited by hand.',
  obicall: { executableSha256: sha256(new Uint8Array(fs.readFileSync(exe))), coreLibrary: core },
  demoSha256: sha256(demo),
  variants,
};
const out = path.join(ROOT, 'tests', 'fixtures', 'obicall', 'replay-oracle.json');
fs.writeFileSync(out, `${JSON.stringify(oracle, null, 2)}\n`);
console.log(`${Object.keys(variants).length} recordings -> ${path.relative(ROOT, out)}`);
