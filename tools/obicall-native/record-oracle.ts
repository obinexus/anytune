/**
 * Records what Obicall's native obicall_static_fuse_1d answers to every case of fuse-cases.ts (tests/fixtures/obicall/fuse-oracle.json), through the
 * harness build.sh built against the staged obicall.dll. Never edited by hand.
 *
 *   node tools/obicall-native/record-oracle.ts [path/to/fuse-harness.exe]      (default: .native/fuse-harness.exe)
 */
import { spawnSync } from 'node:child_process';
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { bitsOf, fuseCases } from './fuse-cases.ts';

const ROOT = path.resolve(import.meta.dirname, '..', '..');
const harness = process.argv[2] ?? path.join(ROOT, '.native', 'fuse-harness.exe');

/** Every case through the native harness: one answer a case, `[status, mean bits | null, variance bits | null]`. */
export function askNative(exe: string): [string, string | null, string | null][] {
  const input = fuseCases().map((c) => [c.means.length, ...c.means.map(bitsOf), ...c.variances.map(bitsOf)].join(' ')).join('\n');
  const run = spawnSync(exe, [], { input: `${input}\n`, encoding: 'utf8', maxBuffer: 1 << 26 });
  if (run.status !== 0) throw new Error(`the fusion harness failed: ${run.stderr}`);
  return run.stdout.trim().split(/\r?\n/).map((line) => {
    const match = /^(.*) (\S+) (\S+)$/.exec(line);
    if (!match) throw new Error(`the fusion harness said: ${line}`);
    const [, status, mean, variance] = match as unknown as [string, string, string, string];
    return [status, mean === '-' ? null : mean, variance === '-' ? null : variance];
  });
}

if (import.meta.main) {
  const cases = fuseCases();
  const answers = askNative(harness);
  if (answers.length !== cases.length) throw new Error(`${answers.length} answers to ${cases.length} cases`);
  const dll = path.join(path.dirname(harness), 'obicall.dll');
  const oracle = {
    about: 'What Obicall’s native obicall_static_fuse_1d (the staged obicall.dll of obicall ae5581a) answered to every case of tools/obicall-native/fuse-cases.ts, through tools/obicall-native/fuse-harness.c. Doubles as IEEE-754 bits. Generated by tools/obicall-native/record-oracle.ts; never edited by hand.',
    obicallDllSha256: crypto.createHash('sha256').update(fs.readFileSync(dll)).digest('hex'),
    cases: cases.map((c, i) => ({ name: c.name, means: c.means.map(bitsOf), variances: c.variances.map(bitsOf), native: answers[i] })),
  };
  const out = path.join(ROOT, 'tests', 'fixtures', 'obicall', 'fuse-oracle.json');
  fs.writeFileSync(out, `${JSON.stringify(oracle, null, 1)}\n`);
  console.log(`${cases.length} cases -> ${path.relative(ROOT, out)}`);
}
