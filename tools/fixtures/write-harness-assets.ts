/**
 * Writes src/harness/assets.generated.ts: what the app bundles, as data a module can carry everywhere it runs (the browser, the Android WebView's assets, the
 * Node tests) without a bundler's asset handling:
 *
 *   FUR_ELISE_MIDI_BASE64     tests/fixtures/midi/fur-elise-opening.mid — the bundled song (a public-domain score, encoded for AnyTune)
 *   GUITAR_ARTWORK_DATA_URL   assets/instruments/guitar/yorbederycke-guitar-6755435.svg, the same bytes, base64 — the artwork is never changed
 *   FRETBOARD_MAP             assets/instruments/guitar/fretboard-map.json
 *
 *   node tools/fixtures/write-harness-assets.ts [--check]
 */
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..', '..');
export const OUT = path.join(ROOT, 'src', 'harness', 'assets.generated.ts');

export function harnessAssets(): string {
  const midi = fs.readFileSync(path.join(ROOT, 'tests', 'fixtures', 'midi', 'fur-elise-opening.mid'));
  const svg = fs.readFileSync(path.join(ROOT, 'assets', 'instruments', 'guitar', 'yorbederycke-guitar-6755435.svg'));
  const map = JSON.parse(fs.readFileSync(path.join(ROOT, 'assets', 'instruments', 'guitar', 'fretboard-map.json'), 'utf8'));
  return [
    '/**',
    ' * GENERATED by tools/fixtures/write-harness-assets.ts — do not edit. What the app bundles, as data: the bundled song, the guitar artwork (the supplied',
    ' * file\'s own bytes, base64) and its fretboard map. tests/harness/assets.test.ts checks that this is still what the sources are.',
    ' */',
    "import type { FretboardMap } from '../music/fretboard.ts';",
    '',
    `export const FUR_ELISE_MIDI_BASE64 = '${midi.toString('base64')}';`,
    '',
    `export const GUITAR_ARTWORK_DATA_URL = 'data:image/svg+xml;base64,${svg.toString('base64')}';`,
    '',
    `export const FRETBOARD_MAP: FretboardMap = ${JSON.stringify(map)};`,
    '',
  ].join('\n');
}

if (process.argv[1] !== undefined && path.resolve(process.argv[1]) === path.resolve(import.meta.filename)) {
  const text = harnessAssets();
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(OUT) || fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') !== text) {
      console.error('src/harness/assets.generated.ts is out of date: run node tools/fixtures/write-harness-assets.ts');
      process.exitCode = 1;
    }
  } else {
    fs.writeFileSync(OUT, text);
    console.log(`${path.relative(ROOT, OUT)}: ${text.length} characters`);
  }
}
