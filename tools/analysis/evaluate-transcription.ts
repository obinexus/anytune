/**
 * Measures the import's transcription on a declared fixture and writes docs/evaluation/transcription-synthetic.{json,md}: the Für Elise score
 * (tests/fixtures/midi/fur-elise-opening.mid) rendered as plucked strings, encoded into an MP4 by FFmpeg, decoded by FFmpeg as the import does, transcribed
 * by Basic Pitch, cleaned of octave ghosts — and scored against the score it was made from (onset-only note F1, 50 ms, src/import/transcription.ts).
 *
 * SYNTHETIC: the "performance" is the score, plucked by a synthesiser — no human timing, no piano, no room. The numbers say what the engine and AnyTune's
 * clean-up do with clean plucked tones, not what they do with a recording of a person.
 *
 *   node tools/analysis/evaluate-transcription.ts
 */
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { performance } from 'node:perf_hooks';
import { dropOctaveGhosts, scoreNotes, type NoteScore } from '../../src/import/transcription.ts';
import { ENGINE_SAMPLE_RATE, engineInfo, transcribe } from '../../services/import-worker/src/basic-pitch.ts';
import { decode } from '../../services/import-worker/src/media.ts';
import { findTool } from '../../services/import-worker/src/tools.ts';
import { FUR_ELISE_MIDI, makeMp4, notesOfMidi } from '../fixtures/media.ts';

const ROOT = path.resolve(import.meta.dirname, '..', '..');

async function main(): Promise<void> {
  const ffmpeg = await findTool('ffmpeg');
  if (!ffmpeg.found) throw new Error(ffmpeg.reason);
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'anytune-transcription-'));
  const cases: { name: string; tracks: number[] | null; snrDb?: number }[] = [
    { name: 'melody (right hand), clean', tracks: [1] },
    { name: 'melody (right hand), 20 dB SNR', tracks: [1], snrDb: 20 },
    { name: 'both hands, clean', tracks: null },
    { name: 'both hands, 20 dB SNR', tracks: null, snrDb: 20 },
  ];
  const results: Record<string, { raw: NoteScore; filtered: NoteScore; ghostsDropped: number; audioSeconds: number; transcribeSeconds: number }> = {};
  try {
    for (const c of cases) {
      const truth = notesOfMidi(FUR_ELISE_MIDI, c.tracks);
      const mp4 = makeMp4(ffmpeg.path, truth, dir, c.name.replace(/[^a-z0-9]+/gi, '-'), c.snrDb === undefined ? {} : { snrDb: c.snrDb });
      const audio = await decode(ffmpeg.path, mp4, ENGINE_SAMPLE_RATE, 600);
      if (!audio.ok) throw new Error(audio.message);
      const t0 = performance.now();
      const raw = await transcribe(audio.value);
      const seconds = (performance.now() - t0) / 1000;
      const { kept, dropped } = dropOctaveGhosts(raw);
      const reference = truth.map((n) => ({ key: n.key, onsetSeconds: n.onsetSeconds }));
      results[c.name] = { raw: scoreNotes(reference, raw), filtered: scoreNotes(reference, kept), ghostsDropped: dropped.length, audioSeconds: audio.value.length / ENGINE_SAMPLE_RATE, transcribeSeconds: Math.round(seconds * 10) / 10 };
      console.error(`${c.name}: F1 ${results[c.name]?.raw.f1.toFixed(3)} raw, ${results[c.name]?.filtered.f1.toFixed(3)} without octave ghosts`);
    }
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
  const out = path.join(ROOT, 'docs', 'evaluation');
  fs.mkdirSync(out, { recursive: true });
  const engine = engineInfo();
  fs.writeFileSync(path.join(out, 'transcription-synthetic.json'), `${JSON.stringify({ generatedBy: 'tools/analysis/evaluate-transcription.ts', fixture: 'tests/fixtures/midi/fur-elise-opening.mid, plucked-string synthesis, MP4 (AAC 160 kb/s) via FFmpeg', engine, metric: 'onset-only note precision/recall/F1, 50 ms, exact MIDI key', results }, null, 2)}\n`);
  const pct = (x: number): string => `${(100 * x).toFixed(1)} %`;
  const lines = [
    '# Transcription on a synthetic fixture',
    '',
    '> **SYNTHETIC.** The "performance" is the score itself, plucked by a synthesiser, then encoded to MP4 and decoded as the import decodes: no human timing, no piano, no room, no microphone. These numbers say what the engine and AnyTune\'s clean-up do with clean plucked tones, **not** what they do with a recording of a person, and no accuracy is claimed beyond them.',
    '',
    `How it was measured:`,
    '',
    `- **Engine:** ${engine.name} ${engine.version} (${String(engine.parameters['runtime'])}), with its default post-processing.`,
    '- **Fixture:** `tests/fixtures/midi/fur-elise-opening.mid`.',
    '- **Metric:** onset-only note precision, recall and F1. A note counts when its MIDI key is exact and its onset is within 50 ms.',
    '- **Clean-up:** "raw" is the engine\'s notes. "Without octave ghosts" applies AnyTune\'s documented filter (`src/import/transcription.ts`).',
    '',
    'Generated by `node tools/analysis/evaluate-transcription.ts`. Don\'t edit it by hand.',
    '',
    '| case | notes | raw P / R / F1 | without octave ghosts P / R / F1 | ghosts dropped | onset error median / p95 (ms) | audio s / transcription s |',
    '|---|---:|---|---|---:|---|---|',
    ...Object.entries(results).map(([name, r]) => `| ${name} | ${r.raw.reference} | ${pct(r.raw.precision)} / ${pct(r.raw.recall)} / ${pct(r.raw.f1)} | ${pct(r.filtered.precision)} / ${pct(r.filtered.recall)} / **${pct(r.filtered.f1)}** | ${r.ghostsDropped} | ${r.filtered.onsetErrorMs.median?.toFixed(1) ?? '–'} / ${r.filtered.onsetErrorMs.p95?.toFixed(1) ?? '–'} | ${r.audioSeconds.toFixed(1)} / ${r.transcribeSeconds} |`),
    '',
    'Transcription ran on the development machine\'s CPU in Node (TensorFlow.js, CPU backend). That is why the import runs in the companion worker, not on the phone.',
    '',
  ];
  fs.writeFileSync(path.join(out, 'transcription-synthetic.md'), `${lines.join('\n')}\n`);
  console.error('docs/evaluation/transcription-synthetic.{json,md} written');
}

main().catch((error: unknown) => {
  console.error(error);
  process.exitCode = 1;
});
